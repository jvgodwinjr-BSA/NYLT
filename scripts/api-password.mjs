#!/usr/bin/env node
// Writes api/config.php, which lets the server check the shared password without storing it.
//
//   npm run api-password                 prompts (use the same passphrase as the roster)
//   ROSTER_PASSWORD=... npm run api-password
//
// PBKDF2-SHA256 at 210,000 iterations, the same as the roster. Node computes it here and PHP
// recomputes it per request with hash_pbkdf2, so there is no dependency on either side.
// The resulting file is safe to commit: it holds a salt and a hash, never the password.
import { writeFileSync, mkdirSync } from 'node:fs';
import { randomBytes, pbkdf2Sync } from 'node:crypto';
import { ask } from './encrypt-roster.mjs';

export const ITERATIONS = 210000;
export function configFor(password, salt = randomBytes(16)) {
  const hash = pbkdf2Sync(Buffer.from(password, 'utf8'), salt, ITERATIONS, 32, 'sha256');
  return { iterations: ITERATIONS, salt: salt.toString('base64'), hash: hash.toString('base64') };
}
export const renderConfig = (c) => `<?php
// Generated by \`npm run api-password\`. Verifies the shared password for api/placements.php.
// A .php file so the server executes it instead of serving its contents. Holds a salt and a
// PBKDF2-SHA256 hash — never the password itself — so committing it is safe.
return [
  'iterations' => ${c.iterations},
  'salt' => '${c.salt}',
  'hash' => '${c.hash}',
];
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const argv = process.argv.slice(2);
  const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
  let pw = opt('--password') ?? process.env.ROSTER_PASSWORD;
  if (!pw) {
    pw = await ask('Shared password (same one that unlocks the roster): ');
    if (pw !== await ask('Again: ')) { console.error('Passwords differ.'); process.exit(1); }
  }
  if (pw.length < 8) { console.error('Use at least 8 characters.'); process.exit(1); }
  const out = opt('--out') ?? 'api/config.php';
  mkdirSync('api', { recursive: true });
  writeFileSync(out, renderConfig(configFor(pw)));
  console.log(`Wrote ${out}. Commit it and push; the site can then verify the shared password.`);
  console.log('Anyone with that password can now read and edit the shared schedule.');
}
